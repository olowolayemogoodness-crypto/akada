// Builds the web version of Edu into www/ (used for edu.joinedulink.com and the Android app).
//   www/index.html  Edu: learning map, shorts, notes, quizzes (phone first)
//   www/cbt.html    the full JAMB CBT mock exam (best on a computer)
// Run: npm run build:web
import { cpSync, rmSync, mkdirSync, readFileSync, writeFileSync, readdirSync, statSync, existsSync, renameSync } from 'node:fs';
import { join, relative } from 'node:path';
import { createHash } from 'node:crypto';

const ROOT = new URL('..', import.meta.url).pathname;
const OUT = join(ROOT, 'www');
const nm = (p) => join(ROOT, 'node_modules', p);

rmSync(OUT, { recursive: true, force: true });
cpSync(join(ROOT, 'app'), OUT, { recursive: true, filter: (src) => !/\/(lab|shorts)\.html$/.test(src) });

// Libraries the CBT uses, copied next to the app (no internet needed).
mkdirSync(join(OUT, 'vendor/three/addons/controls'), { recursive: true });
cpSync(nm('three/build/three.module.js'), join(OUT, 'vendor/three/three.module.js'));
if (existsSync(nm('three/build/three.core.js'))) cpSync(nm('three/build/three.core.js'), join(OUT, 'vendor/three/three.core.js')); // newer three splits the build
cpSync(nm('three/examples/jsm/controls/OrbitControls.js'), join(OUT, 'vendor/three/addons/controls/OrbitControls.js'));
mkdirSync(join(OUT, 'vendor/gsap'), { recursive: true });
for (const f of readdirSync(nm('gsap'))) if (f.endsWith('.js')) cpSync(nm(`gsap/${f}`), join(OUT, `vendor/gsap/${f}`));

// Swap the pages: Edu becomes the home page, the CBT moves to cbt.html.
renameSync(join(OUT, 'index.html'), join(OUT, 'cbt.html'));
renameSync(join(OUT, 'edu.html'), join(OUT, 'index.html'));
const cbt = join(OUT, 'cbt.html');
writeFileSync(cbt, readFileSync(cbt, 'utf8')
  .replace('"../node_modules/three/build/three.module.js"', '"./vendor/three/three.module.js"')
  .replace('"../node_modules/three/examples/jsm/"', '"./vendor/three/addons/"')
  .replace('"../node_modules/gsap/index.js"', '"./vendor/gsap/index.js"'));

// The custom domain for GitHub Pages. Only written once the DNS record exists (set EDU_DOMAIN in the workflow);
// until then the site is served at https://olowolayemogoodness-crypto.github.io/akada/
if (process.env.EDU_DOMAIN) writeFileSync(join(OUT, 'CNAME'), process.env.EDU_DOMAIN + '\n');

// Offline support on the web: a service worker that keeps a copy of every file.
const files = [];
const walk = (d) => { for (const f of readdirSync(d)) { const p = join(d, f); statSync(p).isDirectory() ? walk(p) : files.push(relative(OUT, p)); } };
walk(OUT);
const list = files.filter((f) => !/^(CNAME|sw\.js|downloads\/)/.test(f)).sort();
const hash = createHash('sha1');
for (const f of list) hash.update(f).update(readFileSync(join(OUT, f)));
const version = hash.digest('hex').slice(0, 10);
writeFileSync(join(OUT, 'sw.js'), `// Generated by scripts/build-web.mjs. Keeps Edu working offline.
const CACHE = 'edu-${version}';
const FILES = ${JSON.stringify(['./', ...list])};
self.addEventListener('install', (e) => { e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting())); });
self.addEventListener('activate', (e) => { e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', (e) => {
  if (e.request.method !== 'GET' || new URL(e.request.url).origin !== location.origin) return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then((hit) => hit || fetch(e.request)));
});
`);

const size = list.reduce((a, f) => a + statSync(join(OUT, f)).size, 0);
console.log(`Built www/ (${list.length} files, ${(size / 1048576).toFixed(1)} MB, version ${version})`);
if (!existsSync(join(OUT, 'index.html'))) process.exit(1);
